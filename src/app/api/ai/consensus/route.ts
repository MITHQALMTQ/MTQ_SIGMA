// POST /api/ai/consensus
//
// Task 47 — ad-hoc multi-provider consensus query. Body: { question: string }
// (max 500 chars; control chars stripped). The SAME question goes to the
// voter panel (every keyed provider: NVIDIA · OpenRouter · Gemini); the
// engine aggregates:
//   * field-majority vote over the JSON fields each model returns
// The response carries the consensus result, the per-vote attestation
// (provider/model/latency/parse status — never raw vote content, which stays
// server-side), the agreement score, and the persisted run id.
//
// ADVISORY ONLY — never writes engine state. Rate-limited at the strict "ai"
// bucket (5 req/IP/min): one call = 3 model generations server-side.

import { NextResponse } from "next/server";
import { runConsensus } from "@/lib/ai/consensus";
import { AI_CONSENSUS_ENABLED, anyConsensusProviderKeyed } from "@/lib/ai/keys";
import { rateLimit, getClientIP } from "@/lib/mtq/rate-limit";

export const dynamic = "force-dynamic";
export const revalidate = 0;

const SYSTEM = [
  "You are a cross-verification analyst for the MTQΣ digital-currency platform.",
  "MTQΣ fact sheet (authoritative — cite from here, never invent):",
  "MTQΣ is a fully-reserved digital currency (testnet pilot) with a 7-component chain-linked reference basket (§9.2);",
  "Reserve Ratio target 1.10, stress floor 1.05, hard solvency floor 1.00 (§14.2); LCR target 1.20;",
  "mint/redeem fees 10/10 bps (§14.5); price safety band 0.50–2.00 with §3.6 price events;",
  "single-component weight envelope 10–32% (§8.1); daily rebalance turnover cap 2%;",
  "risk states: NORMAL → GUARDED → ALERT → EMERGENCY (§14.1); geopolitical eject ladder §11.",
  "Answer the operator's question with a JSON object of exactly this shape:",
  '{"answer": "<your 2-4 sentence answer>", "confidence": "<high|medium|low>", "caveat": "<one-sentence caveat or empty string>"}',
  "The values must be YOUR actual content (never placeholders). Do not invent facts. If unsure, say so in the caveat and lower the confidence.",
].join(" ");

function sanitize(raw: unknown): string | null {
  if (typeof raw !== "string") return null;
  const stripped = raw.replace(/[\x00-\x08\x0B\x0C\x0E-\x1F\x7F]/g, "").trim();
  if (stripped.length === 0 || stripped.length > 500) return null;
  return stripped;
}

export async function POST(req: Request) {
  const ip = getClientIP(req);
  const rl = await rateLimit(ip, "ai");
  if (!rl.allowed) {
    return NextResponse.json(
      { error: "Rate limit exceeded", retryAfter: 60 },
      {
        status: 429,
        headers: { "Retry-After": String(Math.ceil((rl.resetAt - Date.now()) / 1000)) },
      },
    );
  }
  if (!AI_CONSENSUS_ENABLED) {
    return NextResponse.json({ error: "AI consensus disabled", model: "disabled" }, { status: 503 });
  }
  if (!anyConsensusProviderKeyed()) {
    return NextResponse.json(
      { error: "No consensus-capable AI provider key configured (see .env.local — NVIDIA · OpenRouter · Google AI Studio/Gemini are the keyed free providers)" },
      { status: 503, headers: { "X-RateLimit-Remaining": String(rl.remaining) } },
    );
  }

  let body: { question?: unknown } = {};
  try {
    body = await req.json();
  } catch {
    return NextResponse.json({ error: "Invalid JSON body" }, { status: 400 });
  }

  const question = sanitize(body.question);
  if (!question) {
    return NextResponse.json(
      { error: "Body must include 'question' (1-500 chars, no control characters)" },
      { status: 400 },
    );
  }

  try {
    const con = await runConsensus<Record<string, unknown>>({
      taskType: "adhoc",
      system: SYSTEM,
      user: question,
      mode: "field-majority",
      voters: 3,
      maxTokens: 400,
      temperature: 0.2,
    });

    return NextResponse.json(
      {
        question,
        status: con.status,
        ok: con.ok,
        result: con.result,
        consensus: {
          votersAsked: con.votersAsked,
          votersOk: con.votersOk,
          quorumMet: con.quorumMet,
          agreement: con.agreement,
          durationMs: con.durationMs,
          runId: con.runId,
          promptDigest: con.promptDigest,
          votes: con.votes.map((v) => ({
            provider: v.provider,
            model: v.model,
            role: v.role,
            ok: v.ok,
            parsed: v.parsed,
            latencyMs: v.latencyMs,
            fieldAgreement: v.fieldAgreement,
            error: v.error,
          })),
        },
        disclaimer: "AI-generated by multi-model consensus. Informational only — not financial advice. The engine math is the source of truth.",
      },
      {
        headers: {
          "X-RateLimit-Remaining": String(rl.remaining),
          "Cache-Control": "no-store",
        },
      },
    );
  } catch (e) {
    console.error("[api/ai/consensus] run failed:", e instanceof Error ? e.message : e);
    return NextResponse.json({ error: "Consensus run failed" }, { status: 502 });
  }
}
